export type TranslationKey = Key
export const dictionaries: Record<Lang, Record<Key, string>> = { ko, en, zh, ja, fr }

export const translate = (lang: Lang, key: Key, vars?: Record<string, string | number>) => {
  let text = dictionaries[lang][key]
  if (vars) for (const [name, value] of Object.entries(vars)) text = text.replace(`{${name}}`, String(value))
  return text
}

const LOCALES: Record<Lang, string> = { ko: "ko-KR", en: "en-US", zh: "zh-CN", ja: "ja-JP", fr: "fr-FR" }
export const localeOf = (lang: Lang) => LOCALES[lang]
